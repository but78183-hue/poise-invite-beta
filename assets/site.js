const supportedLanguages = Object.keys(translations);
const languageSelect = document.getElementById("language-select");

function preferredLanguage() {
  const queryLanguage = new URLSearchParams(window.location.search).get("lang");
  const storedLanguage = window.localStorage.getItem("poise.site.language");
  const browserLanguage = navigator.language;
  const browserMatch = supportedLanguages.find((language) => browserLanguage === language || browserLanguage.startsWith(`${language}-`));
  return [queryLanguage, storedLanguage, browserMatch, "en"].find((language) => supportedLanguages.includes(language));
}

function applyLanguage(language, updateUrl = false) {
  const copy = translations[language] || translations.en;
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title = copy.metaTitle;
  document.querySelector('meta[name="description"]').setAttribute("content", copy.metaDescription);
  document.querySelector('meta[property="og:title"]').setAttribute("content", copy.metaTitle);
  document.querySelector('meta[property="og:description"]').setAttribute("content", copy.metaDescription);
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = copy[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute("aria-label", value);
  });
  languageSelect.value = language;
  const officialSiteLink = document.querySelector("[data-official-site-link]");
  if (officialSiteLink) {
    const isLocal = ["localhost", "127.0.0.1"].includes(window.location.hostname);
    const siteUrl = new URL(officialSiteLink.href);
    if (isLocal) {
      siteUrl.protocol = window.location.protocol;
      siteUrl.hostname = window.location.hostname;
      siteUrl.port = "4178";
      siteUrl.pathname = language === "zh-Hant" ? "/zh-hant/" : "/";
    } else {
      siteUrl.pathname = language === "zh-Hant" ? "/poise-site/zh-hant/" : "/poise-site/";
    }
    if (language === "en" || language === "zh-Hant") siteUrl.searchParams.delete("lang");
    else siteUrl.searchParams.set("lang", language);
    officialSiteLink.href = siteUrl.toString();
  }
  window.localStorage.setItem("poise.site.language", language);
  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", language);
    window.history.replaceState({}, "", url);
  }
}

languageSelect.addEventListener("change", (event) => applyLanguage(event.target.value, true));
applyLanguage(preferredLanguage());
